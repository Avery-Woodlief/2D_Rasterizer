import numpy as np
from buffers.shape_geometry import polygon

WIDTH = 512
HEIGHT = 512

framebuffer = np.zeros(
    (HEIGHT, WIDTH, 4),
    dtype=np.uint8
)

from math import sin, cos, pi
from random import Random

rng = Random(9217)

POLYGON_LIMIT = 2000
polygon_count = 0


# ============================================================
# WRAPPER
# ============================================================

def P(points, color, layer):
    global polygon_count

    if polygon_count >= POLYGON_LIMIT:
        return

    polygon(
        framebuffer,
        points,
        color=color,
        layer=layer
    )

    polygon_count += 1


# ============================================================
# HELPERS
# ============================================================

def diamond(cx, cy, rx, ry, color, layer):
    P(
        [
            (cx, cy - ry),
            (cx + rx, cy),
            (cx, cy + ry),
            (cx - rx, cy)
        ],
        color,
        layer
    )


def patch(cx, cy, rx, ry, color, layer, sides=6):
    points = []

    rotation = rng.uniform(
        0,
        2 * pi
    )

    for i in range(sides):
        angle = (
            rotation +
            (2 * pi * i / sides)
        )

        scale = rng.uniform(
            0.82,
            1.15
        )

        points.append(
            (
                int(cx + cos(angle) * rx * scale),
                int(cy + sin(angle) * ry * scale)
            )
        )

    P(
        points,
        color,
        layer
    )


def clamp(value):
    return max(
        0,
        min(
            255,
            int(value)
        )
    )


def rgba(r, g, b):
    return (
        clamp(r),
        clamp(g),
        clamp(b),
        255
    )


def inside_face(x, y):

    nx = (
        x - 256
    ) / 135

    ny = (
        y - 258
    ) / 185

    return (
        nx * nx +
        ny * ny
    ) <= 1.0


