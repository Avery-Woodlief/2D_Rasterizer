def draw_iris(cx, cy):

    # dark outer iris
    points = []

    for i in range(16):
        a = (
            i /
            16 *
            2 *
            pi
        )

        points.append(
            (
                int(cx + cos(a) * 13),
                int(cy + sin(a) * 13)
            )
        )

    P(
        points,
        (48, 65, 55, 255),
        8
    )

    # green inner iris
    points = []

    for i in range(14):
        a = (
            i /
            14 *
            2 *
            pi
        )

        points.append(
            (
                int(cx + cos(a) * 10),
                int(cy + sin(a) * 10)
            )
        )

    P(
        points,
        (100, 116, 76, 255),
        8
    )

    # amber center
    points = []

    for i in range(12):
        a = (
            i /
            12 *
            2 *
            pi
        )

        points.append(
            (
                int(cx + cos(a) * 6),
                int(cy + sin(a) * 6)
            )
        )

    P(
        points,
        (125, 101, 50, 255),
        8
    )

    # pupil
    points = []

    for i in range(12):
        a = (
            i /
            12 *
            2 *
            pi
        )

        points.append(
            (
                int(cx + cos(a) * 4),
                int(cy + sin(a) * 4)
            )
        )

    P(
        points,
        (19, 17, 15, 255),
        8
    )

    # specular highlight
    diamond(
        cx - 4,
        cy - 5,
        2,
        2,
        (255, 252, 238, 255),
        9
    )


