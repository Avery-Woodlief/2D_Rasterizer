    def pine_tree(
        x,
        base_y,
        width,
        height,
        color
    ):

        trunk_width = max(
            3,
            width // 8
        )

        # trunk
        P(
            [
                (x - trunk_width, base_y),
                (x + trunk_width, base_y),
                (x + trunk_width, base_y - height // 2),
                (x - trunk_width, base_y - height // 2)
            ],
            (37, 30, 29, 255),
            8
        )

        top = base_y - height

        sections = 4

        for i in range(sections):

            y = (
                top +
                i * (height // 5)
            )

            half_width = int(
                width *
                (
                    0.45 +
                    i * 0.20
                )
            )

            section_height = height // 3

            P(
                [
                    (x, y),
                    (
                        x - half_width,
                        y + section_height
                    ),
                    (
                        x + half_width,
                        y + section_height
                    )
                ],
                color,
                8
            )


